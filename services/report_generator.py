"""
Report Generator Service for GOAT AI.
Uses ReportLab to dynamically construct a downloadable PDF summary of the analysis.
"""

import io
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors


def generate_pdf_report(analysis_data: Dict[str, Any]) -> io.BytesIO:
    """
    Generate an in-memory PDF report from analysis results.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    
    # Custom Brand Styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=26,
        textColor=colors.HexColor('#0f172a')
    )
    subtitle_style = ParagraphStyle(
        'DocSub',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#64748b')
    )
    h2_style = ParagraphStyle(
        'SectionH2',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#1e293b'),
        spaceBefore=14,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#334155')
    )
    badge_style = ParagraphStyle(
        'Badge',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=11,
        leading=14,
        textColor=colors.HexColor('#059669') if analysis_data.get('is_verified') else colors.HexColor('#d97706')
    )
    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Italic'],
        fontName='Helvetica-Oblique',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#94a3b8')
    )

    story = []

    # Header
    story.append(Paragraph("GOAT AI — Resume & Job Match Assessment", title_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph("Generated by GOAT AI Next-Gen Career Intelligence Platform", subtitle_style))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#818cf8'), spaceAfter=14))

    # Overview Table
    score = round(analysis_data.get('match_score', 0))
    status_text = "Verified — Score Threshold Met (>= 85%)" if analysis_data.get('is_verified') else "Not Verified — Below 85%"
    
    overview_data = [
        [Paragraph("<b>Target Role:</b>", body_style), Paragraph(str(analysis_data.get('target_role', 'General Role')), body_style)],
        [Paragraph("<b>Document Source:</b>", body_style), Paragraph(str(analysis_data.get('source_type', 'Resume Document')), body_style)],
        [Paragraph("<b>Overall Match Score:</b>", body_style), Paragraph(f"<b>{score}%</b>", title_style)],
        [Paragraph("<b>Algorithmic Status:</b>", body_style), Paragraph(status_text, badge_style)],
        [Paragraph("<b>Assessment Date:</b>", body_style), Paragraph(str(analysis_data.get('created_at', 'Today')), body_style)]
    ]
    t_overview = Table(overview_data, colWidths=[150, 390])
    t_overview.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#e2e8f0')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0, 0), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    story.append(t_overview)
    story.append(Spacer(1, 14))

    # Matched Skills Section
    story.append(Paragraph("Matched Capabilities", h2_style))
    matched_skills = analysis_data.get('matched_skills', [])
    if matched_skills:
        skills_text = ", ".join(matched_skills)
        story.append(Paragraph(f"<b>Identified in Resume:</b> {skills_text}", body_style))
    else:
        story.append(Paragraph("No direct technical matches detected against listed job requirements.", body_style))

    story.append(Spacer(1, 10))

    # Missing Skills Section
    story.append(Paragraph("Missing Skills & Recommended Areas", h2_style))
    missing_skills = analysis_data.get('missing_skills', [])
    if missing_skills:
        missing_text = ", ".join(missing_skills)
        story.append(Paragraph(f"<b>Employer Requirements Missing from Resume:</b> {missing_text}", body_style))
    else:
        story.append(Paragraph("Excellent! All primary technical requirements identified in the job were found.", body_style))

    story.append(Spacer(1, 14))

    # Roadmap Section
    roadmap = analysis_data.get('roadmap', {})
    if roadmap:
        story.append(Paragraph("Personalized Acceleration Roadmap", h2_style))
        for level in ['beginner', 'intermediate', 'advanced']:
            items = roadmap.get(level, [])
            if items:
                story.append(Paragraph(f"<b>{level.capitalize()} Milestone:</b>", body_style))
                for item in items[:2]:
                    story.append(Paragraph(f"• {item}", body_style))
                story.append(Spacer(1, 4))

    story.append(Spacer(1, 16))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=10))

    # Mandatory Disclaimer
    disclaimer_text = (
        "<b>Important Notice:</b> This report is generated through computational NLP matching and text similarity analysis. "
        "The 85% verification score is an internal heuristic benchmark measuring keyword alignment. It does NOT constitute legal, "
        "academic, or official employment verification, nor does it guarantee hiring success. Never falsify resume information."
    )
    story.append(Paragraph(disclaimer_text, disclaimer_style))

    doc.build(story)
    buffer.seek(0)
    return buffer
